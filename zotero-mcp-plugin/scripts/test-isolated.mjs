import { spawn } from "node:child_process";
import process from "node:process";
import console from "node:console";
import {
  access,
  lstat,
  mkdir,
  readdir,
  readFile,
  writeFile,
} from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sandbox = join(root, ".scaffold", "test");
const marker = join(sandbox, "PLUS_TEST_SANDBOX.json");
const binary = process.env.ZOTERO_PLUGIN_ZOTERO_BIN_PATH;
if (!binary)
  throw new Error(
    "请通过 ZOTERO_PLUGIN_ZOTERO_BIN_PATH 指定 Zotero 可执行文件；不猜测或使用默认 profile",
  );
await access(binary);
for (const path of [root, join(root, ".scaffold"), sandbox]) {
  const stat = await lstat(path).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (stat?.isSymbolicLink())
    throw new Error("隔离测试目录不能是 symlink/junction");
}
const contents = await readdir(sandbox).catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return [];
});
if (contents.length) {
  const saved = JSON.parse(await readFile(marker, "utf8").catch(() => "null"));
  if (
    saved?.owner !== "zotero-mcp-plus-isolated-test" ||
    saved?.version !== 1
  ) {
    throw new Error(
      "现有 .scaffold/test 不是本测试创建的目录，拒绝清空；请检查现有内容",
    );
  }
}
for (const name of ["profile", "data", "resource"]) {
  const stat = await lstat(join(sandbox, name)).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (stat?.isSymbolicLink())
    throw new Error("测试子目录不能是 symlink/junction");
}
await mkdir(sandbox, { recursive: true });
await writeFile(
  marker,
  JSON.stringify({ owner: "zotero-mcp-plus-isolated-test", version: 1 }),
);
// scaffold 的测试资源仍从旧 chai.js URL 下载；使用锁文件中已安装的 Chai 本地生成浏览器包。
const chaiCache = join(root, ".scaffold", "cache", "chai.js");
const cachedChai = await readFile(chaiCache, "utf8").catch((error) => {
  if (error.code !== "ENOENT") throw error;
  return null;
});
const chaiMarker = "// Generated by zotero-mcp-plus isolated tests";
if (cachedChai !== null && !cachedChai.startsWith(chaiMarker)) {
  throw new Error("存在非本测试生成的 Chai 缓存，请先检查，不自动覆盖");
}
const { build } = await import("esbuild");
await build({
  stdin: {
    contents: "import * as chai from 'chai'; globalThis.chai = chai;",
    resolveDir: root,
  },
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "firefox140",
  outfile: chaiCache,
  banner: { js: chaiMarker },
});
console.log(
  "仅启动 .scaffold/test/profile 与 .scaffold/test/data 隔离实例；不会停止或修改主 Zotero。",
);
const child = spawn(
  process.execPath,
  [
    join(
      root,
      "node_modules",
      "zotero-plugin-scaffold",
      "bin",
      "zotero-plugin.mjs",
    ),
    "test",
    "--no-watch",
  ],
  {
    cwd: root,
    env: { ...process.env, MOZ_NO_REMOTE: "1" },
    stdio: "inherit",
  },
);
child.on("error", (error) => {
  console.error(error.message);
  process.exitCode = 1;
});
child.on("exit", async (code) => {
  process.exitCode = code ?? 1;
  try {
    for (const [name, minimum] of [
      [
        "plus-integration-result.json",
        process.env.PLUS_TEST_NETWORK_PDF === "1" ? 16 : 15,
      ],
      ["upstream-writes-result.json", 4],
      ["recovery-result.json", 3],
      ...(process.env.ZOTERO_PLUS_LEGACY_XPI
        ? [["coexistence-result.json", 2]]
        : []),
    ]) {
      const result = JSON.parse(
        await readFile(join(sandbox, "data", name), "utf8"),
      );
      if (
        result.total < minimum ||
        result.passed !== result.total ||
        result.failed !== 0
      )
        throw new Error(`${name}: 测试未全部通过`);
    }
  } catch (error) {
    console.error(`集成验证未完成：${error.message}`);
    process.exitCode = 1;
  }
});
